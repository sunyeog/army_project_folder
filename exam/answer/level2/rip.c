#include <stdio.h>	// puts

/*
** [rip] 처음부터 작성
**
** 핵심 아이디어 (2단계):
**   1) 몇 개를 지워야 하는지(최소 개수)를 먼저 센다
**   2) 글자마다 "그대로 둔다 / 공백으로 지운다" 두 갈래로 나누되
**      딱 그 개수만큼만 지우고, 결과가 균형이면 출력
**
** 1) 최소 개수 세기 (한 번 훑기):
**      '('  -> open++
**      ')'  -> 짝지을 '('가 있으면 open--, 없으면 close++ (남는 ')')
**      끝까지 가서 남은 open = 남는 '('
**      최소 = open + close
**
**   예) "()())()"
**       ( ) ( ) ) ( )
**       1 0 1 0 ↑ 1 0     <- ↑에서 짝이 없음: close = 1
**       최소 = 0 + 1 = 1
**
** 2) 균형 검사: 왼쪽부터 세면서 한 번도 0 밑으로 안 가고, 끝이 0
*/

/* ============================================================
** min_remove: 지워야 하는 최소 개수
** ============================================================ */
int	min_remove(char *s)
{
	int	open = 0;
	int	close = 0;
	int	i = 0;

	while (s[i])
	{
		if (s[i] == '(')
			open++;
		else if (s[i] == ')')
		{
			if (open > 0)
				open--;	// 짝 맞춤
			else
				close++;	// 짝 없는 ')'
		}
		i++;
	}
	return (open + close);	// 남는 '(' + 남는 ')'
}

/* ============================================================
** is_balanced: 공백은 무시하고 괄호 균형 검사
** ============================================================ */
int	is_balanced(char *s)
{
	int	cnt = 0;
	int	i = 0;

	while (s[i])
	{
		if (s[i] == '(')
			cnt++;
		else if (s[i] == ')')
		{
			cnt--;
			if (cnt < 0)	// ')'가 먼저 나와 버림
				return (0);
		}
		i++;
	}
	return (cnt == 0);
}

/* ============================================================
** solve
**   i    : 지금 결정할 글자 위치
**   left : 앞으로 더 지워야 하는 개수
** ============================================================ */
void	solve(char *s, int i, int left)
{
	char	c;

	if (s[i] == '\0')	// 끝까지 결정함
	{
		if (left == 0 && is_balanced(s))
			puts(s);
		return ;
	}
	// 갈래 1: 이 글자를 그대로 둔다
	solve(s, i + 1, left);
	// 갈래 2: 아직 지울 개수가 남았으면 이 글자를 공백으로 지운다
	if (left > 0)
	{
		c = s[i];
		s[i] = ' ';	// 지우기
		solve(s, i + 1, left - 1);
		s[i] = c;	// 되돌리기
	}
}

int	main(int ac, char **av)
{
	if (ac != 2)
		return (1);
	solve(av[1], 0, min_remove(av[1]));
	return (0);
}
